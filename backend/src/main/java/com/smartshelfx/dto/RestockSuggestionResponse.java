package com.smartshelfx.dto;

import java.math.BigDecimal;

/**
 * RestockSuggestionResponse
 * 
 * Provides automated replenishment recommendations for products that have
 * reached or breached their minimum stock thresholds.
 */
public class RestockSuggestionResponse {

    private Long productId;
    private String productName;
    private String productSku;
    private String categoryName;
    private Long vendorId;
    private String vendorName;
    private Integer currentStock;
    private Integer minStockThreshold;
    private Integer reorderQuantity;
    private Integer suggestedOrderQuantity;
    private BigDecimal unitCost;
    private BigDecimal estimatedTotalCost;
    private String priority; // "HIGH" (Out of Stock), "MEDIUM" (Low Stock)
    private String reason;

    public RestockSuggestionResponse() {
    }

    // Getters and Setters
    public Long getProductId() {
        return productId;
    }

    public void setProductId(Long productId) {
        this.productId = productId;
    }

    public String getProductName() {
        return productName;
    }

    public void setProductName(String productName) {
        this.productName = productName;
    }

    public String getProductSku() {
        return productSku;
    }

    public void setProductSku(String productSku) {
        this.productSku = productSku;
    }

    public String getCategoryName() {
        return categoryName;
    }

    public void setCategoryName(String categoryName) {
        this.categoryName = categoryName;
    }

    public Long getVendorId() {
        return vendorId;
    }

    public void setVendorId(Long vendorId) {
        this.vendorId = vendorId;
    }

    public String getVendorName() {
        return vendorName;
    }

    public void setVendorName(String vendorName) {
        this.vendorName = vendorName;
    }

    public Integer getCurrentStock() {
        return currentStock;
    }

    public void setCurrentStock(Integer currentStock) {
        this.currentStock = currentStock;
    }

    public Integer getMinStockThreshold() {
        return minStockThreshold;
    }

    public void setMinStockThreshold(Integer minStockThreshold) {
        this.minStockThreshold = minStockThreshold;
    }

    public Integer getReorderQuantity() {
        return reorderQuantity;
    }

    public void setReorderQuantity(Integer reorderQuantity) {
        this.reorderQuantity = reorderQuantity;
    }

    public Integer getSuggestedOrderQuantity() {
        return suggestedOrderQuantity;
    }

    public void setSuggestedOrderQuantity(Integer suggestedOrderQuantity) {
        this.suggestedOrderQuantity = suggestedOrderQuantity;
    }

    public BigDecimal getUnitCost() {
        return unitCost;
    }

    public void setUnitCost(BigDecimal unitCost) {
        this.unitCost = unitCost;
    }

    public BigDecimal getEstimatedTotalCost() {
        return estimatedTotalCost;
    }

    public void setEstimatedTotalCost(BigDecimal estimatedTotalCost) {
        this.estimatedTotalCost = estimatedTotalCost;
    }

    public String getPriority() {
        return priority;
    }

    public void setPriority(String priority) {
        this.priority = priority;
    }

    public String getReason() {
        return reason;
    }

    public void setReason(String reason) {
        this.reason = reason;
    }
}
